#!/usr/bin/env python3
"""Render a human-readable TRANSCRIPT.md next to each arm's raw/ directory.

  python3 render.py control treatment raw-files 'haiku/*' 'nocode/*' 'rerun-fresh-clone/*'

For every directory given (the parent of a raw/ folder) this writes <dir>/TRANSCRIPT.md. Per answer:
the exact prompt and system prompt (from <qid>-r<n>.meta.json), each tool call (name and input,
cut at 400 characters), a short slice of its result (cut at 500), and the final answer verbatim.
The .jsonl files stay the evidence; this is only a reading aid. Nothing here is edited or summarised
beyond those cuts (and /home/<user> shown as <HOME>), and nothing under raw/ is touched.
"""
import glob
import json
import pathlib
import re
import sys

CALL_MAX, RESULT_MAX = 400, 500
HOME_RE = re.compile(r"/home/[A-Za-z0-9_.-]+")  # the only rewrite: the machine's home directory shows as <HOME>
HEADER = "Generated by render.py from raw/*.jsonl and *.meta.json; nothing edited."


def cut(text, n):
    text = text if isinstance(text, str) else json.dumps(text, ensure_ascii=False)
    return text if len(text) <= n else text[:n] + f" ... [cut, {len(text) - n} more characters in the .jsonl]"


def fence(text):
    text = HOME_RE.sub("<HOME>", text.rstrip("\n"))
    f = "```"
    while f in text:
        f += "`"
    return f"{f}\n{text}\n{f}"


def key(p):
    m = re.match(r"([QH])(\d+)-r(\d+)\.jsonl$", p.name)
    return (0 if m.group(1) == "Q" else 1, int(m.group(2)), int(m.group(3))) if m else (2, 0, 0)


def render_answer(jl):
    stem = jl.name[: -len(".jsonl")]
    meta_p = jl.with_name(stem + ".meta.json")
    meta = json.loads(meta_p.read_text()) if meta_p.exists() else {}
    out = [f"## {stem}", ""]
    bits = [f"arm `{meta.get('arm', '?')}`", f"model `{meta.get('model', '?')}`"]
    if meta.get("tools"):
        bits.append(f"tools `{meta['tools']}`")
    if meta.get("effort"):
        bits.append(f"effort `{meta['effort']}`")
    if "wall_s" in meta:
        bits.append(f"wall {meta['wall_s']} s")
    out += [", ".join(bits), ""]
    out += ["**Prompt** (from the .meta.json):", "", fence(meta.get("prompt", "(no .meta.json)")), ""]
    out += ["**System prompt:**", "", fence(meta.get("system_prompt", "(no .meta.json)")), ""]
    calls, final, names = [], None, {}
    events = [json.loads(l) for l in jl.read_text().splitlines() if l.strip()]
    n = 0
    for e in events:
        if e.get("type") == "assistant":
            for b in e["message"].get("content", []):
                if b.get("type") == "tool_use":
                    n += 1
                    names[b["id"]] = n
                    out += [f"**Tool call {n}: {b['name']}**", "", fence(cut(json.dumps(b["input"], ensure_ascii=False), CALL_MAX)), ""]
                elif b.get("type") == "text" and b.get("text", "").strip():
                    out += ["Model text between calls:", "", fence(cut(b["text"], RESULT_MAX)), ""]
        elif e.get("type") == "user" and isinstance(e["message"].get("content"), list):
            for r in e["message"]["content"]:
                if r.get("type") == "tool_result":
                    c = r.get("content")
                    if isinstance(c, list):
                        c = "\n".join(x.get("text", json.dumps(x)) if isinstance(x, dict) else str(x) for x in c)
                    tag = " (error)" if r.get("is_error") else ""
                    out += [f"Result of call {names.get(r.get('tool_use_id'), '?')}{tag}:", "", fence(cut(c or "", RESULT_MAX)), ""]
        elif e.get("type") == "result":
            final = e
    out += ["**Final answer** (verbatim):", ""]
    if final is None:
        out += ["(no result event in this transcript)", ""]
    else:
        out += [fence(final.get("result", "")), ""]
        out += [f"_{n} tool calls; list price ${final.get('total_cost_usd', 0):.4f}; stop reason {final.get('stop_reason')}_", ""]
    return "\n".join(out)


def render_dir(d):
    d = pathlib.Path(d)
    raw = d / "raw"
    files = sorted(raw.glob("*.jsonl"), key=key) if raw.is_dir() else []
    if not files:
        return None
    parts = [f"# Transcripts: `{d.as_posix()}`", "", HEADER, "",
             f"{len(files)} answers, in question order. The evidence is `raw/<qid>-r<n>.jsonl` (every event, untouched) and "
             "`raw/<qid>-r<n>.meta.json` (prompt, system prompt, settings, exact command). Tool calls are cut at "
             f"{CALL_MAX} characters and results at {RESULT_MAX}; the final answer is whole. "
             "The one rewrite: the home directory of the machine that ran it appears as `<HOME>`.", ""]
    parts += [render_answer(f) for f in files]
    (d / "TRANSCRIPT.md").write_text("\n".join(parts))
    return len(files)


if __name__ == "__main__":
    targets = [p for a in sys.argv[1:] for p in sorted(glob.glob(a))]
    if not targets:
        sys.exit(__doc__)
    for t in targets:
        n = render_dir(t)
        print(f"{t}: {'wrote TRANSCRIPT.md for %d answers' % n if n else 'no raw/*.jsonl, skipped'}")
